from numpy.lib.mixins import NDArrayOperatorsMixin
class W(NDArrayOperatorsMixin):
    def __init__(s, v): s.v = np.asarray(v)
    def __array_ufunc__(s, uf, m, *i, **k):
        i = [x.v if isinstance(x, W) else x for x in i]
        return W(getattr(uf, m)(*i, **k))
    def __repr__(s): return f"W({s.v!r})"
P("mixin matmul", lambda: W([[1, 2]]) @ W([[1], [2]]))
